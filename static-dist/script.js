const languageToggle = document.querySelector("[data-lang-toggle]");
const navToggle = document.querySelector(".nav-toggle");
const inquiryForm = document.querySelector("#inquiry");
const formStatus = document.querySelector("[data-form-status]");
const salesEmail = "sales@yuanfangdown.com";

function setLanguage(lang) {
  const dictionary = translations[lang];
  document.documentElement.lang = lang === "zh" ? "zh-CN" : "en";
  document.title = dictionary.metaTitle;
  document.querySelector('meta[name="description"]').setAttribute("content", dictionary.metaDescription);

  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const key = node.getAttribute("data-i18n");
    if (dictionary[key]) {
      node.textContent = dictionary[key];
    }
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((node) => {
    const key = node.getAttribute("data-i18n-placeholder");
    if (dictionary[key]) {
      node.setAttribute("placeholder", dictionary[key]);
    }
  });

  languageToggle.textContent = lang === "zh" ? "English" : "中文";
  localStorage.setItem("yuanfang-lang", lang);
}

function getCurrentLanguage() {
  return localStorage.getItem("yuanfang-lang") || "zh";
}

languageToggle.addEventListener("click", () => {
  setLanguage(getCurrentLanguage() === "zh" ? "en" : "zh");
});

navToggle.addEventListener("click", () => {
  const isOpen = document.body.classList.toggle("nav-open");
  navToggle.setAttribute("aria-expanded", String(isOpen));
});

document.querySelectorAll(".site-nav a").forEach((link) => {
  link.addEventListener("click", () => {
    document.body.classList.remove("nav-open");
    navToggle.setAttribute("aria-expanded", "false");
  });
});

inquiryForm.addEventListener("submit", (event) => {
  event.preventDefault();
  const formData = new FormData(inquiryForm);
  const lang = getCurrentLanguage();
  const dictionary = translations[lang];
  const subject = lang === "zh" ? "远方羽绒官网询价" : "Yuanfang Down Website Inquiry";
  const lines =
    lang === "zh"
      ? [
          `采购品类：${formData.get("product") || ""}`,
          `绒子含量：${formData.get("content") || ""}`,
          `采购数量：${formData.get("quantity") || ""}`,
          `联系方式：${formData.get("contact") || ""}`,
        ]
      : [
          `Product: ${formData.get("product") || ""}`,
          `Down content: ${formData.get("content") || ""}`,
          `Quantity: ${formData.get("quantity") || ""}`,
          `Contact: ${formData.get("contact") || ""}`,
        ];

  formStatus.textContent = dictionary.formStatus;
  window.location.href = `mailto:${salesEmail}?subject=${encodeURIComponent(subject)}&body=${encodeURIComponent(lines.join("\n"))}`;
});

setLanguage(getCurrentLanguage());
